#!/bin/sh
set -eu

SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PROJECT_DIR=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
SECRETS_DIR="$PROJECT_DIR/.secrets"

AUTHORITY_CONTROL_PLANE_PUBLIC_KEY_FILE=${AUTHORITY_CONTROL_PLANE_PUBLIC_KEY_FILE:-$SECRETS_DIR/control-plane-ed25519.pub.pem}
AUTHORITY_SSH_CA_KEY_FILE=${AUTHORITY_SSH_CA_KEY_FILE:-$SECRETS_DIR/ssh-ca}
AUTHORITY_SSH_CA_PUBLIC_KEY_FILE=${AUTHORITY_SSH_CA_PUBLIC_KEY_FILE:-$SECRETS_DIR/ssh-ca.pub}
AUTHORITY_DB_HOST=${AUTHORITY_DB_HOST:-$("$SCRIPT_DIR/authority-agent.sh" run _db:status | awk '/^ip: / {print $2;exit}')}
AUTHORITY_DB_PASSWORD_FILE=${AUTHORITY_DB_PASSWORD_FILE:-$SECRETS_DIR/authority-db-password}
AUTHORITY_PKI_PUBLIC_ORIGIN=${AUTHORITY_PKI_PUBLIC_ORIGIN:-http://10.0.3.1:3001}
export AUTHORITY_DB_HOST AUTHORITY_DB_PASSWORD_FILE AUTHORITY_PKI_PUBLIC_ORIGIN
AUTHORITY_MTLS_CA_KEY_FILE=${AUTHORITY_MTLS_CA_KEY_FILE:-$SECRETS_DIR/mtls-ca-key.pem}
AUTHORITY_MTLS_CA_CERTIFICATE_FILE=${AUTHORITY_MTLS_CA_CERTIFICATE_FILE:-$SECRETS_DIR/mtls-ca-cert.pem}
export AUTHORITY_CONTROL_PLANE_PUBLIC_KEY_FILE AUTHORITY_SSH_CA_KEY_FILE AUTHORITY_SSH_CA_PUBLIC_KEY_FILE AUTHORITY_MTLS_CA_KEY_FILE AUTHORITY_MTLS_CA_CERTIFICATE_FILE

if [ ! -s "$AUTHORITY_CONTROL_PLANE_PUBLIC_KEY_FILE" ]; then
    echo "credential-issuer: control-plane public key not found; start the control plane first" >&2
    exit 1
fi

if [ "${AUTHORITY_POC_PREBUILT:-}" = 1 ]; then
    exec "$PROJECT_DIR/target/debug/authority-credential-issuer"
fi

exec cargo run --offline -p authority-credential-issuer
